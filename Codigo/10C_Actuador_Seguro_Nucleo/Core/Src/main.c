static uint16_t EncoderSamplePosition(void)
{
  /* La resta modular conserva el signo incluso al cruzar 0/65535. Se lee
     cada vuelta para evitar un wrap completo entre muestras. */
  const uint16_t counter = (uint16_t)__HAL_TIM_GET_COUNTER(&htim3);
  const int16_t delta = (int16_t)(uint16_t)(counter - encoderLastCounter);
  encoderLastCounter = counter;
  encoderPositionX4 = (int32_t)((uint32_t)encoderPositionX4 + (uint32_t)(int32_t)delta);
  return counter;
}

static void EncoderTelemetry_Loop(void)
{
  EncoderSamplePosition();
  const uint32_t now = HAL_GetTick();
  const uint32_t telemetryElapsedMs = now - encoderLastTelemetryMs;
  const uint32_t telemetryPeriodMs = StreamActuator_StreamActive() ? 50u : 1000u;
  if (telemetryElapsedMs >= telemetryPeriodMs) {
    if (StreamActuator_EncoderTelemetry(encoderPositionX4, encoderCachedSpeedTenths,
        telemetryElapsedMs > 65535u ? 65535u : (uint16_t)telemetryElapsedMs)) {
      /* Guardar el instante de la muestra realmente enviada, no el intento.
         Si UART/RX estan ocupados, reintentar en la siguiente vuelta con
         posicion nueva y dt real, sin esperar otros 50 ms ni crear rafagas. */
      encoderLastTelemetryMs = now;
    }
  }
}

static void EncoderDiagnostic_Loop(void)
{
  const uint16_t counter = EncoderSamplePosition();
  const uint32_t now = HAL_GetTick();
  const uint32_t elapsedMs = now - encoderLastPrintMs;
  if (elapsedMs < 1000u) return;
  encoderLastPrintMs = now;
  const int32_t intervalDelta = (int32_t)((uint32_t)encoderPositionX4 -
                                       (uint32_t)encoderLastPrintedX4);
  encoderLastPrintedX4 = encoderPositionX4;
  const uint16_t speedTenths = BeltSpeedTenths(intervalDelta, elapsedMs);
  encoderCachedSpeedTenths = speedTenths;
  char line[168];
  const int length = snprintf(line, sizeof(line),
      "[ENCODER] pos_x4=%ld delta_1s=%ld tim3=%u Z_pulses=%lu A=%u B=%u Z=%u speed_mm_s=%u.%u dt_ms=%lu D_mm=49\r\n",
      (long)encoderPositionX4, (long)intervalDelta, (unsigned)counter,
      (unsigned long)encoderIndexEdges,
      (unsigned)HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_6),
      (unsigned)HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_5),
      (unsigned)HAL_GPIO_ReadPin(GPIOC, GPIO_PIN_2),
      speedTenths / 10u, speedTenths % 10u, (unsigned long)elapsedMs);
  if (length > 0 && length < (int)sizeof(line)) {
    HAL_UART_Transmit(&huart2, (uint8_t *)line, (uint16_t)length, 20u);
  }
}
